export interface ItemDef {
  id: string;
  name: string;
  description: string;
  /** gear is worn in a slot; an active is used from a quick slot; a material is spent by a rule. */
  kind: 'gear' | 'active' | 'material';
  slot?: GearSlot;
  weapon?: WeaponDef;
  mods?: Partial<Mods>;
  use?: UseDef;
  /** Materials: what the rule in contest.ts does with one, in the HUD's words. */
  rule?: string;
}

const arc = (range: number, halfArcCos: number, damage: number, cooldownTicks: number, extra: Partial<WeaponDef> = {}): WeaponDef =>
  ({ pattern: 'arc', range, halfArcCos, halfWidth: 0, damage, cooldownTicks, ...extra });
const line = (range: number, halfWidth: number, damage: number, cooldownTicks: number, extra: Partial<WeaponDef> = {}): WeaponDef =>
  ({ pattern: 'line', range, halfArcCos: 1, halfWidth, damage, cooldownTicks, ...extra });
const weapon = <I extends string>(id: I, name: string, def: WeaponDef, description: string) =>
  ({ id, name, kind: 'gear', slot: 'weapon', weapon: def, description }) as const satisfies ItemDef;
const boots = <I extends string>(id: I, name: string, mods: Partial<Mods>, description: string) =>
  ({ id, name, kind: 'gear', slot: 'boots', mods, description }) as const satisfies ItemDef;
const charm = <I extends string>(id: I, name: string, mods: Partial<Mods>, description: string) =>
  ({ id, name, kind: 'gear', slot: 'charm', mods, description }) as const satisfies ItemDef;
const active = <I extends string>(id: I, name: string, use: UseDef, description: string) =>
  ({ id, name, kind: 'active', use, description }) as const satisfies ItemDef;
const material = <I extends string>(id: I, name: string, rule: string, description: string) =>
  ({ id, name, kind: 'material', rule, description }) as const satisfies ItemDef;

