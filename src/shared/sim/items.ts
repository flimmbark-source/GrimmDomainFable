/**
 * How a weapon hits.
 *   arc  : everything in a wedge in front of the hero, out to `range`.
 *   line : the first enemy along a narrow line, out to `range`; cover stops it.
 */
export interface WeaponDef {
  pattern: 'arc' | 'line';
  range: number;
  /** arc: cosine of half the wedge angle. */
  halfArcCos: number;
  /** line: half the width of the shot. */
  halfWidth: number;
  damage: number;
  cooldownTicks: number;
  /** Metres a struck enemy is shoved back; negative pulls it towards you. Walls still stop it. */
  knockback?: number;
  /** Damage per second, for this many ticks, after the hit. */
  bleed?: { dps: number; ticks: number };
  /** The target moves at 60% speed for this many ticks. */
  slowTicks?: number;
  /** The target cannot act for this many ticks. */
  stunTicks?: number;
  /** Share of damage dealt that heals the wielder. */
  lifesteal?: number;
  /** line: hits every enemy on the line, not only the first. */
  pierce?: boolean;
  /** Makes no noise. */
  silent?: boolean;
  /** Damage multiplier when striking a target from behind. */
  backstab?: number;
  /** Damage multiplier against a target below 35% health. */
  execute?: number;
  /** Damage multiplier against a target at full health. */
  opener?: number;
  vsMonsters?: number;
  vsHeroes?: number;
}

