export type ItemId = (typeof LIST)[number]['id'];
export const ITEM_IDS = LIST.map((def) => def.id) as ItemId[];
export const ITEMS = Object.fromEntries(LIST.map((def) => [def.id, def])) as unknown as Record<ItemId, ItemDef & { id: ItemId }>;

export function isItemId(value: unknown): value is ItemId {
  return typeof value === 'string' && Object.hasOwn(ITEMS, value);
}

export function isGearSlot(value: unknown): value is GearSlot {
  return value === 'weapon' || value === 'boots' || value === 'charm';
}

export type Equipment = Record<GearSlot, ItemId | null>;

/** What a hero's worn gear makes it capable of. Derived on demand, so a change of gear takes effect at once. */
export type GearStats = Mods & { weapon: WeaponDef | null };

export function gearStats(equipment: Equipment): GearStats {
  const stats = { weapon: (equipment.weapon && ITEMS[equipment.weapon].weapon) || null } as GearStats;
  for (const key of MOD_KEYS) stats[key] = MOD_INFO[key].kind === 'mul' ? 1 : 0;
  for (const slot of ['boots', 'charm'] as const) {
    const mods = equipment[slot] ? ITEMS[equipment[slot]].mods : undefined;
    if (!mods) continue;
    for (const key of MOD_KEYS) {
      const value = mods[key];
      if (value === undefined) continue;
      const kind = MOD_INFO[key].kind;
      stats[key] = kind === 'mul' ? stats[key] * value : kind === 'add' ? stats[key] + value : Math.max(stats[key], value);
    }
  }
  return stats;
}

export function weaponOf(equipment: Equipment): WeaponDef | null {
  return gearStats(equipment).weapon;
}

export function salveHeal(equipment: Equipment): number {
  return Math.round(30 * gearStats(equipment).salve);
}

function weaponText(w: WeaponDef): string {
  const shape = w.pattern === 'line' ? `Straight shot · range ${w.range} m` : `${w.halfArcCos <= 0.1 ? 'Wide sweep' : w.halfArcCos > 0.8 ? 'Thrust' : 'Sweep'} · reach ${w.range} m`;
  const rate = Math.round((30 / w.cooldownTicks) * 10) / 10;
  const extra: string[] = [];
  if (w.knockback) extra.push(w.knockback > 0 ? `knocks back ${w.knockback} m` : `pulls ${-w.knockback} m`);
  if (w.bleed) extra.push(`bleeds ${w.bleed.dps}/s for ${seconds(w.bleed.ticks)}`);
  if (w.slowTicks) extra.push(`slows for ${seconds(w.slowTicks)}`);
  if (w.stunTicks) extra.push(`stuns for ${seconds(w.stunTicks)}`);
  if (w.lifesteal) extra.push(`heals you for ${Math.round(w.lifesteal * 100)}% of damage`);
  if (w.pierce) extra.push('pierces every enemy on the line');
  if (w.silent) extra.push('silent');
  if (w.backstab) extra.push(`×${w.backstab} from behind`);
  if (w.execute) extra.push(`×${w.execute} below 35% health`);
  if (w.opener) extra.push(`×${w.opener} against the unhurt`);
  if (w.vsMonsters) extra.push(`×${w.vsMonsters} against monsters`);
  if (w.vsHeroes) extra.push(`×${w.vsHeroes} against heroes`);
  return [`${shape} · ${w.damage} damage · ${rate}/s`, ...extra].join(' · ');
}

function useText(use: UseDef): string {
  switch (use.kind) {
    case 'heal': return `Restores ${use.amount} health${use.selfSlowTicks ? ` · slows you for ${seconds(use.selfSlowTicks)}` : ''}`;
    case 'regen': return `Restores ${use.perSecond} health per second for ${seconds(use.ticks)}`;
    case 'smoke': return `Breaks pursuit within ${use.radius} m · unseen for ${seconds(use.ticks)}`;
    case 'veil': return `Unseen for ${seconds(use.ticks)} · attacking ends it`;
    case 'lure': return `Noise ${use.distance} m ahead, heard ${use.radius} m from there`;
    case 'haste': return `Speed +35% for ${seconds(use.ticks)}`;
    case 'guard': return `Damage taken −50% for ${seconds(use.ticks)}`;
    case 'fury': return `Damage +50% for ${seconds(use.ticks)}`;
    case 'cleanse': return `Ends bleed, slow and stun · immune for ${seconds(use.immuneTicks)}`;
    case 'bomb': return `${use.damage} damage in a ${use.radius} m burst, ${use.distance} m ahead`;
    case 'flash': return `Stuns enemies within ${use.radius} m for ${seconds(use.stunTicks)}`;
    case 'caltrops': return `Slows enemies within ${use.radius} m for ${seconds(use.slowTicks)}`;
    case 'knife': return `${use.damage} damage to the first enemy within ${use.range} m ahead`;
    case 'horn': return `You and allies within ${use.radius} m gain haste for ${seconds(use.ticks)}`;
    case 'purge': return `Removes ${Math.round(use.fraction * 100)}% corruption from the wayshrine you stand in`;
  }
}

/** One line saying what an item does, in numbers, for the HUD. No two items share one. */
export function effectText(def: ItemDef): string {
  if (def.weapon) return weaponText(def.weapon);
  if (def.mods) return MOD_KEYS.flatMap((key) => (def.mods![key] === undefined ? [] : [MOD_INFO[key].text(def.mods![key]!)])).join(' · ');
  if (def.use) return useText(def.use);
  return def.rule ?? '';
}
