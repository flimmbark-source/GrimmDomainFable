// Chooses a reachable, open spot in Orchard Vale for every item that is not
// part of a starting kit, and writes src/shared/sim/finds.ts. The first 27
// finds are placed by hand along the routes the playtest steps use; the rest
// are spread over the whole region on a deterministic grid.
//
//   npx tsx scripts/place-finds.ts
import { writeFileSync } from 'node:fs';
import { isBlocked } from '../src/shared/sim/geometry.ts';
import { ITEMS, ITEM_IDS, type ItemId } from '../src/shared/sim/items.ts';
import { boundsOf, getMap } from '../src/shared/sim/map.ts';
import { findPath } from '../src/shared/sim/nav.ts';

const HAND: [ItemId, number, number, number][] = [
  ['sling', 1, -78, 12], ['salve', 2, -66, 12.5], ['herb', 3, -64, -2], ['springheel_boots', 1, -48, 12], ['spiral_charm', 1, -30, 12],
  ['herb', 2, -12, -30], ['apple', 2, -82, 13], ['stone', 3, -72, 11.5], ['softsole_boots', 1, -58, 12.5], ['twin_knives', 1, -70, -6],
  ['smoke', 2, -66, -22], ['dusk_charm', 1, -52, -30], ['billhook', 1, 2, 4], ['cheese', 2, 6, 12], ['coin', 5, 30, 14],
  ['ironbark_charm', 1, 3, 37.5], ['hatchet', 1, -40, 30], ['tonic', 2, 40, 36], ['catspaw_boots', 1, 50, 12], ['hand_crossbow', 1, 69, 13.2],
  ['thorn_charm', 1, -43.6, -54.6], ['scroll', 1, -30, -50], ['cudgel', 1, -10, -45], ['lockpicks', 1, 10, -34], ['whetstone_charm', 1, 20, -20],
  ['courier_boots', 1, 30, -30], ['tumbler_boots', 1, 60, -40],
];
const STARTING: ItemId[] = ['dagger', 'salve', 'cleaver', 'javelin'];
const KEEP_CLEAR = [{ x: -3, z: -28, r: 6 }, { x: -60, z: 22, r: 5 }, { x: -24, z: -32, r: 5 }];

const map = getMap('orchard_vale_v1');
const b = boundsOf(map);
const spawn = map.spawns[4]!;
const placed = HAND.map(([item, count, x, z]) => ({ item, count, x, z }));
const rest = ITEM_IDS.filter((id) => !STARTING.includes(id) && !placed.some((p) => p.item === id));

// Candidate spots on a jittered grid, most spread-out first.
const spots: { x: number; z: number }[] = [];
let seed = 12345;
const rand = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 4294967296);
for (let x = b.minX + 6; x <= b.maxX - 6; x += 7) for (let z = b.minZ + 6; z <= b.maxZ - 6; z += 7) {
  const p = { x: Math.round((x + (rand() - 0.5) * 3) * 2) / 2, z: Math.round((z + (rand() - 0.5) * 3) * 2) / 2 };
  if (isBlocked(map, p.x, p.z, 1.2)) continue;
  if (KEEP_CLEAR.some((k) => Math.hypot(p.x - k.x, p.z - k.z) < k.r) || map.spawns.some((s) => Math.hypot(p.x - s.x, p.z - s.z) < 5)) continue;
  const path = findPath(map, 0.5, spawn, p);
  if (!path || Math.hypot(path.at(-1)!.x - p.x, path.at(-1)!.z - p.z) > 0.3) continue;
  spots.push(p);
}
for (const item of rest) {
  // Farthest-point choice: the open spot farthest from everything placed so far.
  let best = -1;
  let bestD = -1;
  spots.forEach((s, i) => {
    const d = Math.min(...placed.map((p) => Math.hypot(p.x - s.x, p.z - s.z)));
    if (d > bestD) { bestD = d; best = i; }
  });
  if (best < 0 || bestD < 3) throw new Error(`no room left for ${item}`);
  const kind = ITEMS[item].kind;
  placed.push({ item, count: kind === 'gear' ? 1 : kind === 'active' ? 2 : 3, ...spots.splice(best, 1)[0]! });
}
const rows = placed.map((p, id) => `  { id: ${id}, item: '${p.item}', count: ${p.count}, x: ${p.x}, z: ${p.z} },`).join('\n');
writeFileSync(new URL('../src/shared/sim/finds.ts', import.meta.url), `/**
 * Where every find lies in Orchard Vale. GENERATED by scripts/place-finds.ts:
 * edit the hand-placed list or the rules there and run it again.
 *
 * The first 27 are placed by hand along the west road and the routes the
 * playtest steps use. The rest are spread over the region so that every item
 * in the catalogue can be obtained. Placement is provisional (P-26).
 */
import type { ItemId } from './items.ts';

export const FINDS: { id: number; item: ItemId; count: number; x: number; z: number }[] = [
${rows}
];
`);
console.log(`placed ${placed.length} finds; closest pair ${Math.min(...placed.flatMap((a, i) => placed.slice(i + 1).map((c) => Math.hypot(a.x - c.x, a.z - c.z)))).toFixed(1)} m`);
