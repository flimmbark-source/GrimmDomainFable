// Writes docs/production/orchard-vale-items.md from the catalogue, so the
// reference can never drift from what the server simulates.
//   npx tsx scripts/list-items.ts
import { writeFileSync } from 'node:fs';
import { FINDS } from '../src/shared/sim/finds.ts';
import { ITEMS, ITEM_IDS, effectText } from '../src/shared/sim/items.ts';

const where = (x: number, z: number) => `${z < -12 ? 'north' : z > 20 ? 'south' : 'mid'}-${x < -30 ? 'west' : x > 30 ? 'east' : 'centre'} (${x}, ${z})`;
const section = (title: string, pick: (id: string) => boolean) => {
  const rows = ITEM_IDS.filter(pick).map((id) => {
    const find = FINDS.filter((f) => f.item === id).map((f) => `${where(f.x, f.z)}${f.count > 1 ? ` ×${f.count}` : ''}`).join('; ');
    return `| ![](../../public/art/items/${id}.svg) | ${ITEMS[id].name} | ${effectText(ITEMS[id])} | ${find || 'starting kit'} |`;
  });
  return `## ${title} (${rows.length})\n\n| | Item | Effect | Found |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n`;
};
const text = `# Orchard Vale item catalogue

GENERATED by \`scripts/list-items.ts\` from \`src/shared/sim/items.ts\` and \`finds.ts\`. Do not edit by hand.

All ${ITEM_IDS.length} items are playtest proposals (P-24 to P-26 in the [decision register](../decisions.md)). Icons are original vector stand-ins generated by \`scripts/make-item-icons.mjs\`; replace any file in \`public/art/items\` to give an item painted art. "Found" is the map area and coordinates of each find. Every Light Hero collects their own share.

${section('Weapons', (id) => ITEMS[id as never].slot === 'weapon')}
${section('Boots', (id) => ITEMS[id as never].slot === 'boots')}
${section('Charms', (id) => ITEMS[id as never].slot === 'charm')}
${section('Usable items', (id) => ITEMS[id as never].kind === 'active')}
${section('Materials', (id) => ITEMS[id as never].kind === 'material')}`;
writeFileSync(new URL('../docs/production/orchard-vale-items.md', import.meta.url), text);
console.log('wrote item reference');
